// ResponseErrorHandler rewrites one GraphQL error immediately before it is written
// to the client, including errors in deferred payloads and subscription events.
// It is meant for redacting or customizing errors based on the error itself.
//
// rawError is the error object as JSON. It is only valid during the call: it must
// not be retained or modified. source identifies the subgraph failure behind the
// error and is nil for errors that do not come from a subgraph, such as non-null
// violations. source must be treated as read-only.
//
// Returning nil keeps the error unchanged. Otherwise the result replaces the error
// and must be a JSON object. A returned error, or a result that is not a JSON
// object, writes an "Internal server error" in its place, so a failed redaction
// never falls back to the original details.
//
// Invariants:
//   - When no handler is set, errors are written without any additional work.
//   - The handler is called exactly once per error written by a request that is
//     executed. It changes the client response only: the errors recorded on the
//     Context for telemetry are not affected.
//   - Implementations must be concurrency-safe.
//
// Limitations:
//   - Inbound request deduplication stays enabled. A deduplicated request receives
//     the response of the request it waited on, including that request's rewritten
//     errors, and its own handler is not called. Requests are only deduplicated
//     when their operation, variables, forwarded headers and private cache
//     identity match, so the result must not depend on anything else, such as a
//     request ID or a header that is not forwarded to subgraphs. Callers that need
//     this must set ExecutionOptions.DisableInboundRequestDeduplication.
//   - All requests sharing a Resolver should use equivalent handlers. A request
//     without a handler can receive errors rewritten for another request, and a
//     request with a handler can receive errors that were not rewritten.
//   - source.DownstreamErrors holds the subgraph's original errors, before
//     filtering, path rewriting and default code insertion. In wrapped mode it
//     holds all errors of the fetch; in pass-through mode only the error being
//     rewritten. It is empty for errors generated by the engine.
//   - When one fetch produces several engine-generated errors, such as multiple
//     authorization rejections, they share the source of the first one. Rate
//     limit errors have an empty source.Reason.
type ResponseErrorHandler func(ctx context.Context, rawError []byte, source *SubgraphError) ([]byte, error)

var internalServerErrorJSON = []byte(`{"message":"Internal server error"}`)

// responseErrorSources maps error values to the subgraph failure that produced
// them. Values keep their identity when error arrays are merged, so the map
// follows errors from fetch loaders into the response. It is only populated when
// a ResponseErrorHandler is set.
type responseErrorSources map[*astjson.Value]*SubgraphError

func (s responseErrorSources) merge(other responseErrorSources) responseErrorSources {
	if s == nil {
		return other
	}
	maps.Copy(s, other)
	return s
}

func (l *Loader) setErrorSource(value *astjson.Value, source *SubgraphError) {
	if l.errorSources == nil {
		l.errorSources = make(responseErrorSources)
	}
	l.errorSources[value] = source
}

// mergeResult merges a fetch result. With a handler, errors the fetch added
// without a source of their own get the fetch's subgraph error as their source.
func (l *Loader) mergeResult(fetchItem *FetchItem, res *result, items []*astjson.Value) error {
	if l.ctx.ResponseErrorHandler == nil {
		return l.mergeFetchResult(fetchItem, res, items)
	}
	before := 0
	if l.errors != nil {
		before = len(l.errors.GetArray())
	}
	err := l.mergeFetchResult(fetchItem, res, items)
	if l.errors != nil {
		l.setFetchErrorSources(l.errors.GetArray()[before:], fetchItem, res)
	}
	return err
}

// setFetchErrorSources uses the subgraph error recorded for telemetry. When a
// fetch records several, such as one per authorization rejection, the first one
// is used for all of them.
func (l *Loader) setFetchErrorSources(values []*astjson.Value, fetchItem *FetchItem, res *result) {
	if len(values) == 0 {
		return
	}
	source, ok := errors.AsType[*SubgraphError](res.subgraphError)
	if !ok {
		source = NewSubgraphError(res.ds, fetchItem.ResponsePath, "", res.statusCode)
	}
	for _, value := range values {
		if _, ok := l.errorSources[value]; !ok {
			l.setErrorSource(value, source)
		}
	}
}

// downstreamErrorSource decodes the subgraph's errors before the loader filters
// and rewrites them, so the handler can inspect the original paths and extensions.
func (l *Loader) downstreamErrorSource(res *result, fetchItem *FetchItem, value *astjson.Value) (*SubgraphError, error) {
	source := NewSubgraphError(res.ds, fetchItem.ResponsePath, failedToFetchNoReason, res.statusCode)
	if err := json.Unmarshal(value.MarshalTo(nil), &source.DownstreamErrors); err != nil {
		return nil, err
	}
	return source, nil
}

// setPassThroughErrorSources attaches one source per error, each holding only its
// own downstream error.
func (l *Loader) setPassThroughErrorSources(values []*astjson.Value, source *SubgraphError) {
	for i, value := range values {
		perError := *source
		perError.DownstreamErrors = nil
		if i < len(source.DownstreamErrors) {
			perError.DownstreamErrors = source.DownstreamErrors[i : i+1]
		}
		l.setErrorSource(value, &perError)
	}
}

// Subscription event errors bypass the fetch loader, so their source is the trigger.
func (r *Resolvable) setSubscriptionErrorSources(trigger GraphQLSubscriptionTrigger) {
	if r.ctx.ResponseErrorHandler == nil || r.errors == nil {
		return
	}
	for _, value := range r.errors.GetArray() {
		source := NewSubgraphError(DataSourceInfo{ID: trigger.SourceID, Name: trigger.SourceName}, "subscription", "", 0)
		var downstream GraphQLError
		if err := json.Unmarshal(value.MarshalTo(nil), &downstream); err == nil {
			source.DownstreamErrors = []*GraphQLError{&downstream}
		}
		if r.errorSources == nil {
			r.errorSources = make(responseErrorSources)
		}
		r.errorSources[value] = source
	}
}

// printErrorsArray writes the errors array. Without a handler it is a plain copy.
func (r *Resolvable) printErrorsArray() {
	if r.ctx == nil || r.ctx.ResponseErrorHandler == nil {
		r.printNode(r.errors)
		return
	}
	r.printRewrittenErrors()
}

func (r *Resolvable) printRewrittenErrors() {
	r.printBytes(lBrack)
	for i, value := range r.errors.GetArray() {
		if i > 0 {
			r.printBytes(comma)
		}
		r.marshalBuf = value.MarshalTo(r.marshalBuf[:0])
		r.printBytes(rewriteResponseError(r.ctx.ctx, r.ctx.ResponseErrorHandler, r.marshalBuf, r.errorSources[value]))
	}
	r.printBytes(rBrack)
}

func rewriteResponseError(ctx context.Context, handler ResponseErrorHandler, raw []byte, source *SubgraphError) []byte {
	rewritten, err := handler(ctx, raw, source)
	if err != nil {
		return internalServerErrorJSON
	}
	if rewritten == nil {
		return raw
	}
	if !isJSONObject(rewritten) {
		return internalServerErrorJSON
	}
	return rewritten
}

func isJSONObject(data []byte) bool {
	trimmed := bytes.TrimLeft(data, " \t\r\n")
	return len(trimmed) > 0 && trimmed[0] == '{' && json.Valid(trimmed)
}
